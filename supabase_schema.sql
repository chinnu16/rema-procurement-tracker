-- Run this in Supabase SQL Editor before configuring cloud storage.
-- The app reads/writes only this procurement table.
create table if not exists public.procurement (
  id bigint generated by default as identity primary key,
  status text not null default 'In Stock',
  sno text,
  saree_type text not null,
  color text,
  cost_price numeric(12,2),
  selling_price numeric(12,2),
  profits numeric(12,2),
  final_price numeric(12,2),
  comments text,
  customer_details text,
  gst text,
  stock text,
  purchase_date text
);

-- Recommended: enable Row Level Security and configure a private access policy
-- before using this with business data. Do not put a service_role key in a public repo.
alter table public.procurement enable row level security;
